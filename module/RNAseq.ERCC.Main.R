#' Get Script Path
#'
#' Executes GetScriptPath.
#'
#' @param initial.options Argument for GetScriptPath.
#'
#' @return Return value produced by GetScriptPath.
GetScriptPath <- function(initial.options) {
    # return the full path of the current executing script
    # initial.options <- commandArgs(trailingOnly = FALSE)
    file.arg.name <- "--file="
    script.name <- sub(file.arg.name, "", initial.options[grep(file.arg.name, initial.options)])
    script.dirname <- normalizePath(dirname(script.name))
    script.dirname <- paste0(script.dirname, "/")
    return(script.dirname)
}
