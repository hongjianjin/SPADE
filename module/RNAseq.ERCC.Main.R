        comp <- gsub(" ", "", comps[n])
        keywords <- unlist(strsplit(comp, "_[Vv][Ss]_")) # Exp_vs_Ctl ==> Exp, Ctl
        if (keywords[1] == keywords[2]) {
            invalid_comp_inds <- c(invalid_comp_inds, n)
            msg <- paste0("**Error: Invalid comparison! ", comps[n], " [skipped]**")
            cat("\n\n\t", msg, "\n")
            next
        }
    }
