counts_ERCC <- datSet[["counts_ERCC"]]
annotation <- datSet[["annotation"]]
meta <- datSet[["meta"]]
if (flag_ERCC == FALSE) {
    msg_1 <- " based on library size normalization."
} else {
    msg_1 <- " based on ERCC normalization."
}
msg <- paste0("used meta data: ", nrow(meta), " x ", ncol(meta))
