    statDEGs <- data.frame(ID = names(comps), comparison = gsub("_vs_", " vs ", comps), sample_size = statSizes, top_DEGs = statTopn, row.names = NULL)
} else {
    statDEGs <- data.frame(ID = names(comps), comparison = comps, sample_size = statSizes, top_DEGs = statTopn, row.names = NULL)
}

