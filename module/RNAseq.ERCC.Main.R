    # The most fundamental check is the correlation between the known input concentration of each ERCC transcript and the observed counts in your sequencing data.
    correlations <- ErccQC(counts_ERCC, meta)

    # calculate pct_ERCC and norm.factors
    ErccStat <- CalcERCCnormFactor(counts, counts_ERCC, meta, txtFile = NULL)

    ErccStat$ERCC_COR <- correlations[ErccStat$ID]
    statFile <- paste0(prefix, "ERCC_QC_stat.txt")
    write.table(ErccStat, statFile, sep = "\t", quote = FALSE, row.names = FALSE, col.names = TRUE)
    cat("\n[", basename(statFile), "[saved]")
