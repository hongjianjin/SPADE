##################################################################
##################################################################

statDEGs <- NULL
statSizes <- NULL
statTopn <- NULL
statComps <- NULL
numDEGs <- list()
topnDEGs <- list()
for (n in 1:length(comps)) {
    objStr <- names(comps)[n]
    diff_table <- objDE[[objStr]]$DE
    meta1 <- objDE[[objStr]]$meta # subset
    sizes <- table(meta$GROUP) # all samples
    comp <- gsub(" ", "", comps[n])
    if (!any(grepl(".*=\\(.*-.*\\)", comps, ignore.case = T))) {
        # keywords <- unlist(strsplit(comp, "_[Vv][Ss]_")) # Exp_vs_Ctl ==> Exp, Ctl
        comp <- gsub("_[vV][Ss]_", "_vs_", comp)
        keywords <- unlist(strsplit(comp, "_vs_")) # Exp_vs_Ctl ==> Exp, Ctl
        sizes1 <- sizes[toupper(keywords)]
        if (any(is.na(sizes1))) { # partial match
            ExpSize <- length(grep(paste0("^", keywords[1], "$"), meta1$GROUP, ignore.case = T))
            CtlSize <- length(grep(paste0("^", keywords[2], "$"), meta1$GROUP, ignore.case = T))
            sizes1 <- c(ExpSize, CtlSize)
            names(sizes1) <- keywords
        }
        strSizes <- paste0(sizes1, collapse = " vs ")
    } else {
        allGroups <- unlist(strsplit(unlist(strsplit(comp, "[=]"))[2], "[-+]"))
        allGroups <- gsub("\\).*", "", gsub(".*\\(", "", allGroups))
        strSizes <- paste(sizes[allGroups], collapse = " , ")
    }

    statSizes <- c(statSizes, strSizes)
    resDEGs <- GetDEGs(diff_table, cutoff_logFC = cutoff_logFC, cutoff_Pval = cutoff_Pval, cutoff_FDR = cutoff_FDR, topn = topn)
    # tmp <-  data.frame(sample_size=strSizes, up=lengths(geneSet)[1],down= lengths(geneSet)[2], total=sum(lengths(geneSet)[1:2]))
    numDEGs[[length(numDEGs) + 1]] <- resDEGs$numDEGs
    topnDEGs[[length(topnDEGs) + 1]] <- resDEGs$topnDEGs
    topNGenes <- paste0(length(resDEGs$topnDEGs$topUpGenes), " up, ", length(resDEGs$topnDEGs$topDownGenes), " down")
    statTopn <- c(statTopn, topNGenes)
}
